// Generate public/leader-prep.json — the Leader Handout's page-1 summary as
// data the kiosk can render itself.
//
// WHY: the handout is a PDF, shown in an iframe (Chromium's PDF viewer). That
// is the right thing on a TV and the wrong thing on a phone, where a leader
// preparing on the way to church gets a pinch-zoomed page of Letter-sized
// print. The same content as plain text reads anywhere and — unlike a PDF the
// picker streams for a week that isn't the current one — works offline once
// this one small file is cached.
//
// data/leader-handout-summaries.json stays the SINGLE hand-edited source (it
// is a build input, deliberately never served; see CLAUDE.md). This script
// copies only its summary fields into public/. Nothing derived from the video
// itself goes in THIS file; the transcript travels as its own per-week file
// (see below), so leader-prep.json stays small enough to warm at startup.
//
// It also regenerates public/prep-transcripts/ (see
// scripts/build-prep-transcripts.mjs) for the same reason: those served
// copies are derived from data/*-transcript-prose.json and the VTTs, so they
// are rebuilt beside this one rather than drifting until someone remembers.
//
// Usage: node scripts/build-leader-prep.mjs
//        (also run automatically by scripts/render-leader-handouts.mjs, so
//         the served copy can't drift from the handouts)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { writePrepTranscripts } from './build-prep-transcripts.mjs';

const REPO = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const SRC = path.join(REPO, 'data', 'leader-handout-summaries.json');
const OUT = path.join(REPO, 'public', 'leader-prep.json');

const str = (v) => (typeof v === 'string' ? v.trim() : '');
const list = (v) => (Array.isArray(v) ? v.map(str).filter(Boolean) : []);

/** Summaries v2: `questions` is two sets, the leader's own reflection
 *  (`forYou`) and what the leader asks the students (`forGroup`, may be
 *  empty). A v1-shaped plain array is refused rather than guessed at. */
export function questionSets(q, week) {
  if (!q || typeof q !== 'object' || Array.isArray(q)) {
    throw new Error(`week ${week}: questions must be { forYou: [...], forGroup: [...] }`);
  }
  return { forYou: list(q.forYou), forGroup: list(q.forGroup) };
}

export function buildLeaderPrep() {
  const source = JSON.parse(readFileSync(SRC, 'utf8'));
  if (source.version !== 2) throw new Error(`${path.basename(SRC)}: expected version 2, got ${source.version}`);
  const summaries = source.weeks;
  const weeks = {};
  for (const key of Object.keys(summaries).sort((a, b) => Number(a) - Number(b))) {
    const d = summaries[key];
    const week = Number(d.week ?? key);
    if (!Number.isInteger(week) || week < 1) throw new Error(`bad week key ${key}`);
    // A week with no Big Idea is a half-written entry; publishing it would put
    // an empty panel in front of a leader. Better to have no prep for it.
    if (!str(d.bigIdea)) throw new Error(`week ${week}: missing bigIdea`);
    weeks[String(week)] = {
      week,
      title: str(d.title),
      shortTitle: str(d.shortTitle) || str(d.title),
      bigIdea: str(d.bigIdea),
      keyPoints: list(d.keyPoints),
      scriptures: list(d.scriptures),
      questions: questionSets(d.questions, week),
    };
  }
  return {
    // v2: questions became { forYou, forGroup } (the kiosk still reads a
    // cached v1 array as "For you").
    version: 2,
    note:
      'GENERATED by scripts/build-leader-prep.mjs from data/leader-handout-summaries.json. ' +
      'Hand-edit that file, not this one. Page-1 summaries of each Leader Video, written by ' +
      'this church for its own Awana leaders; internal ministry use only.',
    weeks,
  };
}

/** One line per week: the file is warmed at every kiosk startup, so no
 *  indentation, but a change to one week still diffs as one line. */
export function serializeLeaderPrep(data) {
  const weeks = Object.entries(data.weeks).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  return `{\n  "version": ${data.version},\n  "note": ${JSON.stringify(data.note)},\n  "weeks": {\n${weeks.join(',\n')}\n  }\n}\n`;
}

export function writeLeaderPrep() {
  const data = buildLeaderPrep();
  writeFileSync(OUT, serializeLeaderPrep(data));
  const n = Object.keys(data.weeks).length;
  console.log(`leader-prep.json: ${n} week${n === 1 ? '' : 's'} → ${path.relative(REPO, OUT)}`);
  return data;
}

// Run directly (node scripts/build-leader-prep.mjs) but stay importable.
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  writeLeaderPrep();
}
